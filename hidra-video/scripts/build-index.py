    slot("el-bloom", "fx-bloom", BLOOM_START, BLOOM_DUR, 20),
    slot("el-iris", "fx-iris", IRIS_START, IRIS_DUR, 21),
    slot("el-grain", "fx-grain", 0, DUR, 30),
