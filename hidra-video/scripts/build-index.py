def slot(slot_id, cid, start, duration, track):
    return (f'      <div id="{slot_id}" class="slot" data-composition-id="{cid}" '
            f'data-composition-src="compositions/{cid}.html" data-start="{start}" '
            f'data-duration="{duration}" data-track-index="{track}" data-width="1920" data-height="1080"></div>')


slots = [slot("el-paper", "fx-paper", PAPER_START, PAPER_DUR, 1)]
