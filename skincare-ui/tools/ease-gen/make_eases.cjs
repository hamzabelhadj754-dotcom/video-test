// Generates Apple-style spring easing curves (via the `motion` spring solver) as GSAP CustomEase
// paths, so the composition can use physically based springs while staying seek-safe.
//   node tools/ease-gen/make_eases.cjs  ->  assets/eases.js
const { spring } = require("motion");
const fs = require("fs");
const path = require("path");

// name: [visualDuration seconds, bounce]  (bounce 0 = critically damped, no overshoot)
const SPRINGS = {
  springSoft: [0.32, 0],     // content entering: settles, no overshoot
  springMorph: [0.38, 0.05], // the UI shape changing size: tiny, polite settle
  springCam: [0.55, 0],      // camera moves
  springPop: [0.3, 0.1],   // small elements popping in
};

const lines = ["// Generated by tools/ease-gen/make_eases.cjs: do not edit by hand", "(function () {", "  gsap.registerPlugin(CustomEase);"];
for (const [name, [visualDuration, bounce]] of Object.entries(SPRINGS)) {
  const gen = spring({ keyframes: [0, 1], visualDuration, bounce });
  // sample until the spring is done
  const pts = [];
  let total = 0;
  for (let ms = 0; ms <= 5000; ms += 10) {
    const s = gen.next(ms);
    pts.push([ms, s.value]);
    if (s.done) { total = ms; break; }
  }
  if (!total) total = pts[pts.length - 1][0];
  const d = "M0,0 " + pts.slice(1).map(([ms, v]) => "L" + (ms / total).toFixed(4) + "," + v.toFixed(4)).join(" ");
  lines.push(`  CustomEase.create("${name}", "${d}");`);
  lines.push(`  window.SPRING_DUR = window.SPRING_DUR || {}; window.SPRING_DUR.${name} = ${(total / 1000).toFixed(3)};`);
  console.log(name, "settles in", (total / 1000).toFixed(2), "s, points", pts.length);
}
lines.push("})();");
fs.writeFileSync(path.join(__dirname, "..", "..", "assets", "eases.js"), lines.join("\n") + "\n");
